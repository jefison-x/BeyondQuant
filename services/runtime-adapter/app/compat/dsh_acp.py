class AcpTransportError(RuntimeError):
    """A sanitized transport or protocol failure; wire contents are never included."""


class AcpRpcError(RuntimeError):
    """A JSON-RPC error reduced to its method and numeric code."""

    def __init__(self, method: str, code: int) -> None:
        super().__init__(f"official DSH ACP request failed ({method}, code {code})")
        self.method = method
        self.code = code


@dataclass(frozen=True, slots=True)
class AcpNotification:
    """One ordered ACP notification with an Adapter-local sequence number."""

    method: str
    params: dict[str, Any]
    event_sequence: int | None = None


@dataclass(slots=True)
class _Pending:
    event: threading.Event = field(default_factory=threading.Event)
    response: dict[str, Any] | None = None
    error: BaseException | None = None


@dataclass(slots=True)
class _AcpProcess:
    command: tuple[str, ...]
    cwd: Path
    environment: dict[str, str] = field(repr=False)
    process: subprocess.Popen[bytes] | None = field(default=None, repr=False)
    initialized: bool = False
    _writer_lock: threading.Lock = field(default_factory=threading.Lock, repr=False)
    _pending_lock: threading.Lock = field(default_factory=threading.Lock, repr=False)
    _pending: dict[int, _Pending] = field(default_factory=dict, repr=False)
    _notification_lock: threading.Lock = field(default_factory=threading.Lock, repr=False)
    _notifications: dict[str, queue.Queue[AcpNotification | BaseException]] = field(default_factory=dict, repr=False)
    _sequence: dict[str, int] = field(default_factory=dict, repr=False)
    _next_request_id: int = 1
    _fatal: BaseException | None = field(default=None, repr=False)
    _reader: threading.Thread | None = field(default=None, repr=False)
    _closed: bool = False

    def start(self) -> None:
        if self.process is not None:
            raise AcpTransportError("official DSH ACP process is already started")
        try:
            self.cwd.mkdir(parents=True, exist_ok=True)
            self.process = subprocess.Popen(
                self.command,
                cwd=str(self.cwd),
                env=self.environment,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                # ACP stdout is the protocol stream. Never echo child diagnostics,
                # which can include provider or MCP configuration details.
                stderr=subprocess.DEVNULL,
                close_fds=True,
                start_new_session=(os.name == "posix"),
                bufsize=0,
            )
        except (OSError, ValueError):
            raise AcpTransportError("official DSH ACP process could not be started") from None
        if self.process.stdin is None or self.process.stdout is None:
            self.close()
            raise AcpTransportError("official DSH ACP stdio transport is unavailable")
        self._reader = threading.Thread(
            target=self._read_loop,
            name="byq-dsh-acp-reader",
            daemon=True,
        )
        self._reader.start()
        response = self.request(
            "initialize",
            {
                "protocolVersion": _ACP_PROTOCOL_VERSION,
                "clientCapabilities": {},
                "clientInfo": {"name": "beyondquant-runtime-adapter", "version": "0.10"},
            },
            timeout=_REQUEST_TIMEOUT_SECONDS,
        )
        if (not isinstance(response, dict)
                or response.get("protocolVersion") != _ACP_PROTOCOL_VERSION):
            self.close()
            raise AcpTransportError("official DSH ACP protocol version is incompatible")
        self.initialized = True

    def request(self, method: str, params: dict[str, Any], *, timeout: float | None = None) -> Any:
        pending = self._request_async(method, params)
        if not pending.event.wait(timeout):
            self._discard_pending(pending)
            raise AcpTransportError(f"official DSH ACP request timed out ({method})")
        if pending.error is not None:
            raise pending.error
        response = pending.response
        if not isinstance(response, dict):
            raise AcpTransportError("official DSH ACP returned an invalid response")
        if "error" in response:
            error = response["error"]
            code = error.get("code") if isinstance(error, dict) else None
            if isinstance(code, bool) or not isinstance(code, int):
                raise AcpTransportError("official DSH ACP returned a malformed error")
            raise AcpRpcError(method, code)
        if "result" not in response:
            raise AcpTransportError("official DSH ACP response omitted its result")
        return response["result"]

    def request_async(self, method: str, params: dict[str, Any]) -> _Pending:
        return self._request_async(method, params)

    def _request_async(self, method: str, params: dict[str, Any]) -> _Pending:
        self._raise_if_unavailable()
        pending = _Pending()
        with self._pending_lock:
            request_id = self._next_request_id
            self._next_request_id += 1
            self._pending[request_id] = pending
        try:
            self._write({"jsonrpc": "2.0", "id": request_id, "method": method, "params": params})
        except AcpTransportError as error:
            with self._pending_lock:
                self._pending.pop(request_id, None)
            pending.error = error
            pending.event.set()
        return pending

    def await_response(self, pending: _Pending, *, timeout: float | None = None) -> Any:
        if not pending.event.wait(timeout):
            raise AcpTransportError("official DSH ACP prompt did not settle")
        if pending.error is not None:
            raise pending.error
        response = pending.response
        if not isinstance(response, dict):
            raise AcpTransportError("official DSH ACP returned an invalid response")
        if "error" in response:
            error = response["error"]
            code = error.get("code") if isinstance(error, dict) else None
            if isinstance(code, bool) or not isinstance(code, int):
                raise AcpTransportError("official DSH ACP returned a malformed error")
            raise AcpRpcError("session/prompt", code)
        if "result" not in response:
            raise AcpTransportError("official DSH ACP response omitted its result")
        return response["result"]

    def next_notification(self, session_id: str, timeout: float) -> AcpNotification | None:
        self._raise_if_unavailable(allow_closed_queue=True)
        with self._notification_lock:
            events = self._notifications.setdefault(session_id, queue.Queue())
        try:
            value = events.get(timeout=timeout)
        except queue.Empty:
            return None
        if isinstance(value, BaseException):
            raise value
        return value

    def next_sequence(self, session_id: str) -> int:
        with self._notification_lock:
            value = self._sequence.get(session_id, 0) + 1
            self._sequence[session_id] = value
            return value

    def notify(self, method: str, params: dict[str, Any]) -> None:
        self._write({"jsonrpc": "2.0", "method": method, "params": params})

    def _write(self, message: dict[str, Any]) -> None:
        try:
            encoded = json.dumps(message, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
            raw = encoded.encode("utf-8") + b"\n"
        except (TypeError, ValueError, UnicodeError, RecursionError):
            raise AcpTransportError("official DSH ACP request could not be encoded") from None
        if len(raw) > _MAX_FRAME_BYTES:
            raise AcpTransportError("official DSH ACP request exceeded the protocol bound")
        with self._writer_lock:
            self._raise_if_unavailable()
            process = self.process
            if process is None or process.stdin is None:
                raise AcpTransportError("official DSH ACP stdio transport is unavailable")
            try:
                process.stdin.write(raw)
                process.stdin.flush()
            except (BrokenPipeError, OSError, ValueError):
                self._fail(AcpTransportError("official DSH ACP connection was lost"))
                raise AcpTransportError("official DSH ACP connection was lost") from None

    def _read_loop(self) -> None:
        process = self.process
        if process is None or process.stdout is None:
            self._fail(AcpTransportError("official DSH ACP stdio transport is unavailable"))
            return
        try:
            while True:
                raw = process.stdout.readline(_MAX_FRAME_BYTES + 1)
                if not raw:
                    break
                if len(raw) > _MAX_FRAME_BYTES or not raw.endswith(b"\n"):
                    raise AcpTransportError("official DSH ACP response exceeded the protocol bound")
                try:
                    message = json.loads(raw.decode("utf-8"))
                except (UnicodeError, json.JSONDecodeError, RecursionError):
                    raise AcpTransportError("official DSH ACP returned malformed JSON-RPC") from None
                self._dispatch(message)
        except AcpTransportError as error:
            self._fail(error)
            return
        except BaseException:
            self._fail(AcpTransportError("official DSH ACP connection was lost"))
            return
        self._fail(AcpTransportError("official DSH ACP connection was lost"))

    def _dispatch(self, message: object) -> None:
        if not isinstance(message, dict) or message.get("jsonrpc") != "2.0":
            raise AcpTransportError("official DSH ACP returned malformed JSON-RPC")
        if "method" in message:
            method = message.get("method")
            params = message.get("params", {})
            if not isinstance(method, str) or not isinstance(params, dict):
                raise AcpTransportError("official DSH ACP returned malformed JSON-RPC")
            if "id" in message:
                self._handle_server_request(message["id"], method, params)
            else:
                self._handle_notification(method, params)
            return
        request_id = message.get("id")
        if isinstance(request_id, bool) or not isinstance(request_id, int):
            raise AcpTransportError("official DSH ACP returned an unmatched response")
        if ("result" in message) == ("error" in message):
            raise AcpTransportError("official DSH ACP returned malformed JSON-RPC")
        with self._pending_lock:
            pending = self._pending.pop(request_id, None)
        if pending is None:
            raise AcpTransportError("official DSH ACP returned an unmatched response")
        pending.response = message
        pending.event.set()

    def _handle_notification(self, method: str, params: dict[str, Any]) -> None:
        if method != "session/update":
            return
        session_id = params.get("sessionId")
        update = params.get("update")
        if not isinstance(session_id, str) or not session_id or not isinstance(update, dict):
            raise AcpTransportError("official DSH ACP returned a malformed session update")
        sequence = self.next_sequence(session_id)
        event = AcpNotification(method=method, params=params, event_sequence=sequence)
        with self._notification_lock:
            events = self._notifications.setdefault(session_id, queue.Queue())
        events.put(event)

    def _handle_server_request(self, request_id: object, method: str, params: dict[str, Any]) -> None:
        if isinstance(request_id, bool) or not isinstance(request_id, (int, str)):
            raise AcpTransportError("official DSH ACP returned a malformed request")
        if method == "session/request_permission":
            response = self._reject_permission(params)
        else:
            response = {"jsonrpc": "2.0", "id": request_id,
                        "error": {"code": -32601, "message": "Method not found"}}
            self._write(response)
            return
        self._write({"jsonrpc": "2.0", "id": request_id, "result": response})

    @staticmethod
    def _reject_permission(params: dict[str, Any]) -> dict[str, Any]:
        options = params.get("options")
        if not isinstance(options, list):
            raise AcpTransportError("official DSH ACP permission request was malformed")
        for option in options:
            if (isinstance(option, dict) and option.get("kind") == "reject_once"
                    and isinstance(option.get("optionId"), str) and option["optionId"]):
                return {"outcome": {"outcome": "selected", "optionId": option["optionId"]}}
        raise AcpTransportError("official DSH ACP permission request offered no reject option")

    def _discard_pending(self, pending: _Pending) -> None:
        with self._pending_lock:
            stale = [key for key, value in self._pending.items() if value is pending]
            for key in stale:
                self._pending.pop(key, None)

    def _raise_if_unavailable(self, *, allow_closed_queue: bool = False) -> None:
        if self._fatal is not None:
            raise self._fatal
        if self._closed and not allow_closed_queue:
            raise AcpTransportError("official DSH ACP process is closed")
        process = self.process
        if process is not None and process.poll() is not None and self._fatal is None:
            raise AcpTransportError("official DSH ACP process exited")

    def _fail(self, error: BaseException) -> None:
        with self._pending_lock:
            if self._fatal is None:
                self._fatal = error
            pending = tuple(self._pending.values())
            self._pending.clear()
        for item in pending:
            item.error = error
            item.event.set()
        with self._notification_lock:
            queues = tuple(self._notifications.values())
        for events in queues:
            events.put(error)

    def close(self) -> None:
        process = self.process
        if process is None:
            return
        if not self._closed:
            self._closed = True
            try:
                if process.stdin is not None:
                    process.stdin.close()
            except OSError:
                pass
        if process.poll() is None:
            try:
                process.wait(timeout=3.0)
            except (OSError, subprocess.TimeoutExpired):
                self._terminate(process)
        if process.poll() is None:
            raise AcpTransportError("official DSH ACP process exit could not be confirmed")
        reader = self._reader
        if reader is not None and reader is not threading.current_thread():
            reader.join(timeout=1.0)

    @staticmethod
    def _terminate(process: subprocess.Popen[bytes]) -> None:
        try:
            if os.name == "posix":
                os.killpg(process.pid, signal.SIGTERM)
            else:
                process.terminate()
            process.wait(timeout=1.0)
        except (OSError, ProcessLookupError, subprocess.TimeoutExpired):
            try:
                if os.name == "posix":
                    os.killpg(process.pid, signal.SIGKILL)
                else:
                    process.kill()
            except (OSError, ProcessLookupError):
                pass
            try:
                process.wait(timeout=1.0)
            except (OSError, subprocess.TimeoutExpired):
                pass
        if process.poll() is None:
            raise AcpTransportError("official DSH ACP process exit could not be confirmed")


